"""Inbound project briefs: normalise whatever a channel sends into one intake record.

A brief code (``MZ-T2-GLASS-7F3K``, generated by the portfolio's lib/channels.ts) carries the tier
and style a client picked. Web submissions post it as JSON; on WhatsApp, Instagram, Messenger or
email it arrives inside free text. Either way it ends up as an ``Intake``: status
``pending_review`` until an operator routes it into the agent pipeline (or rejects it).
"""

from __future__ import annotations

import hashlib
import json
import re
import secrets
from datetime import datetime, timedelta
from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import EmailStr, Field, TypeAdapter, ValidationError

from agency import db
from agency.jobqueue import DEFAULT_QUEUE_PATH
from agency.schemas import SiteStyle, StrictModel, TemplateTier

# Must match BRIEF_CODE_PATTERN in the portfolio's src/lib/channels.ts.
STYLE_CODES = {
    "MINIMAL": SiteStyle.MINIMALISM,
    "GLASS": SiteStyle.GLASSMORPHISM,
    "BRUTAL": SiteStyle.NEO_BRUTALISM,
    "LIQUID": SiteStyle.LIQUID_GLASS,
}
CODE_OF_STYLE = {style: code for code, style in STYLE_CODES.items()}
SUFFIX_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
BRIEF_CODE = re.compile(r"\bMZ-(T[123])-(MINIMAL|GLASS|BRUTAL|LIQUID)-([A-HJ-NP-Z2-9]{4})\b")
DEDUPE_WINDOW = timedelta(hours=24)


class IntakeError(ValueError):
    """The submission can't be turned into an intake; the message is safe to show the sender."""


class IntakeSource(str, Enum):
    WEB = "web"
    WHATSAPP = "whatsapp"
    INSTAGRAM = "instagram"
    MESSENGER = "messenger"
    EMAIL = "email"


class IntakeStatus(str, Enum):
    PENDING_REVIEW = "pending_review"
    ROUTED = "routed"
    REJECTED = "rejected"


class IntakeContact(StrictModel):
    name: str | None = Field(default=None, max_length=120)
    company: str | None = Field(default=None, max_length=160)
    email: EmailStr | None = None
    phone: str | None = Field(default=None, pattern=r"^\+?[0-9]{7,15}$")
    message: str | None = Field(default=None, max_length=4000)


class Intake(StrictModel):
    """The standard intake record every channel normalises to."""

    intake_id: str
    brief_code: str = Field(pattern=r"^MZ-T[123]-(MINIMAL|GLASS|BRUTAL|LIQUID)-[A-HJ-NP-Z2-9]{4}$")
    tier: TemplateTier
    style: SiteStyle
    contact: IntakeContact
    source: IntakeSource
    status: IntakeStatus = IntakeStatus.PENDING_REVIEW
    received_at: datetime
    job_id: str | None = None
    reviewer_notes: str | None = None


# --------------------------------------------------------------------------- #
# Normalisation
# --------------------------------------------------------------------------- #

_STYLE_ALIASES = {
    **{code.lower(): style for code, style in STYLE_CODES.items()},
    **{style.value: style for style in SiteStyle},
    "glassmorphism": SiteStyle.GLASSMORPHISM,
    "minimal": SiteStyle.MINIMALISM,
    "neobrutalism": SiteStyle.NEO_BRUTALISM,
    "brutalism": SiteStyle.NEO_BRUTALISM,
    "liquidglass": SiteStyle.LIQUID_GLASS,
}
_CONTACT_ALIASES = {
    "name": ("name", "full_name", "fullName"),
    "company": ("company", "business", "business_name", "businessName", "organisation", "organization"),
    "email": ("email", "mail", "email_address", "emailAddress"),
    "phone": ("phone", "whatsapp", "tel", "telephone", "mobile", "phone_number", "phoneNumber"),
    "message": ("message", "notes", "details", "description"),
}


def new_brief_code(tier: TemplateTier, style: SiteStyle) -> str:
    suffix = "".join(secrets.choice(SUFFIX_ALPHABET) for _ in range(4))
    return f"MZ-{tier.value}-{CODE_OF_STYLE[style]}-{suffix}"


def parse_brief_code(text: str) -> tuple[str, TemplateTier, SiteStyle] | None:
    """Find a brief code anywhere in `text` (a field, or a pasted chat message)."""
    match = BRIEF_CODE.search(text.upper())
    if not match:
        return None
    return match.group(0), TemplateTier(match.group(1)), STYLE_CODES[match.group(2)]


def _clean(value: Any, limit: int) -> str | None:
    if value is None:
        return None
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", str(value)).strip()
    return text[:limit] or None


def _tier(value: Any) -> TemplateTier:
    text = str(value).strip().upper()
    text = text if text.startswith("T") else f"T{text}"
    try:
        return TemplateTier(text[:2])
    except ValueError:
        raise IntakeError(f"unknown tier {value!r}; expected T1, T2 or T3") from None


def _style(value: Any) -> SiteStyle:
    key = re.sub(r"[\s_-]+", "", str(value).strip().lower())
    for alias, style in _STYLE_ALIASES.items():
        if key == re.sub(r"[\s_-]+", "", alias):
            return style
    raise IntakeError(f"unknown style {value!r}; expected one of {', '.join(s.value for s in SiteStyle)}")


def _pick(data: dict[str, Any], keys: tuple[str, ...]) -> Any:
    return next((data[k] for k in keys if data.get(k) not in (None, "")), None)


def normalize(payload: Any, *, source: IntakeSource, intake_id: str, received_at: datetime) -> Intake:
    """Turn a channel's payload into an Intake, or raise IntakeError explaining what's missing."""
    if not isinstance(payload, dict):
        raise IntakeError("expected a JSON object")
    contact_in = payload.get("contact") if isinstance(payload.get("contact"), dict) else {}
    merged = {**payload, **contact_in}  # flat or nested contact fields both work

    raw: dict[str, Any] = {field: _pick(merged, keys) for field, keys in _CONTACT_ALIASES.items()}
    message = _clean(raw["message"], 4000)
    phone = _clean(raw["phone"], 40)
    contact_data = {
        "name": _clean(raw["name"], 120),
        "company": _clean(raw["company"], 160),
        "email": _clean(raw["email"], 254),
        "phone": re.sub(r"[\s().-]", "", phone) if phone else None,
        "message": message,
    }
    if not contact_data["email"] and not contact_data["phone"]:
        raise IntakeError("add an email address or a phone number so we can reply")

    # The brief: an explicit code field, else a code inside the message, else tier + style.
    code_text = _pick(payload, ("brief_code", "briefCode", "code", "brief")) or message or ""
    found = parse_brief_code(str(code_text))
    tier_in, style_in = payload.get("tier"), payload.get("style")
    tier = _tier(tier_in) if tier_in not in (None, "") else None
    style = _style(style_in) if style_in not in (None, "") else None
    if found:
        code, code_tier, code_style = found
        if (tier and tier != code_tier) or (style and style != code_style):
            raise IntakeError(f"brief code {code} doesn't match the tier/style sent with it")
        tier, style = code_tier, code_style
    elif tier and style:
        code = new_brief_code(tier, style)
    else:
        raise IntakeError("include a brief code, or both a tier and a style")

    try:
        return Intake(
            intake_id=intake_id,
            brief_code=code,
            tier=tier,
            style=style,
            contact=IntakeContact.model_validate(contact_data),
            source=source,
            received_at=received_at,
        )
    except ValidationError as exc:
        first = exc.errors()[0]
        field = ".".join(str(p) for p in first["loc"])
        raise IntakeError(f"invalid {field}: {first['msg']}") from None



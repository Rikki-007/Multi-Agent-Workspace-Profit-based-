_SCHEMA = """
CREATE TABLE IF NOT EXISTS intakes (
    intake_id   TEXT PRIMARY KEY,
    brief_code  TEXT NOT NULL,
    status      TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    received_at TEXT NOT NULL,
    record      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_intakes_status ON intakes (status, received_at);
CREATE INDEX IF NOT EXISTS ix_intakes_fingerprint ON intakes (fingerprint, received_at);
"""

_INTAKE = TypeAdapter(Intake)


def _fingerprint(intake: Intake) -> str:
    who = (intake.contact.email or "").lower() or intake.contact.phone or ""
    return hashlib.sha256(f"{intake.brief_code}|{who}".encode()).hexdigest()


class IntakeStore:
    def __init__(self, path: str | Path = DEFAULT_QUEUE_PATH) -> None:
        self.path = Path(path)
        db.init(self.path, _SCHEMA)

    def receive(self, payload: Any, source: IntakeSource) -> tuple[Intake, bool]:
        """Normalise and store a submission. Returns (intake, created); a repeat of the same brief
        from the same sender within 24h returns the original instead of a duplicate."""
        now = db.utcnow()
        intake = normalize(payload, source=source, intake_id=f"int_{secrets.token_hex(6)}", received_at=now)
        fingerprint = _fingerprint(intake)
        with db.connect(self.path) as conn:
            row = conn.execute(
                "SELECT record FROM intakes WHERE fingerprint = ? AND received_at >= ? ORDER BY received_at LIMIT 1",
                (fingerprint, db.ts(now - DEDUPE_WINDOW)),
            ).fetchone()
            if row:
                return _INTAKE.validate_json(row["record"]), False
            conn.execute(
                "INSERT INTO intakes (intake_id, brief_code, status, fingerprint, received_at, record) VALUES (?, ?, ?, ?, ?, ?)",
                (intake.intake_id, intake.brief_code, intake.status.value, fingerprint, db.ts(now), intake.model_dump_json()),
            )
        return intake, True

    def get(self, intake_id: str) -> Intake | None:
        with db.connect(self.path) as conn:
            row = conn.execute("SELECT record FROM intakes WHERE intake_id = ?", (intake_id,)).fetchone()
        return _INTAKE.validate_json(row["record"]) if row else None

    def list(self, status: IntakeStatus | None = None, limit: int = 100) -> list[Intake]:
        sql, params = "SELECT record FROM intakes", []
        if status:
            sql += " WHERE status = ?"
            params.append(status.value)
        with db.connect(self.path) as conn:
            rows = conn.execute(sql + " ORDER BY received_at DESC LIMIT ?", (*params, limit)).fetchall()
        return [_INTAKE.validate_json(r["record"]) for r in rows]

    def decide(self, intake_id: str, status: IntakeStatus, *, job_id: str | None = None, notes: str | None = None) -> Intake:
        """Move a pending intake to routed/rejected. Raises KeyError or IntakeError."""
        with db.connect(self.path) as conn:
            row = conn.execute("SELECT record FROM intakes WHERE intake_id = ?", (intake_id,)).fetchone()
            if row is None:
                raise KeyError(intake_id)
            intake = _INTAKE.validate_json(row["record"])
            if intake.status is not IntakeStatus.PENDING_REVIEW:
                raise IntakeError(f"intake {intake_id} is already {intake.status.value}")
            updated = intake.model_copy(update={"status": status, "job_id": job_id, "reviewer_notes": notes})
            conn.execute(
                "UPDATE intakes SET status = ?, record = ? WHERE intake_id = ?",
                (status.value, updated.model_dump_json(), intake_id),
            )
        return updated


def to_json(intake: Intake) -> dict[str, Any]:
    return json.loads(intake.model_dump_json())
